#!/usr/bin/env bash
# Install this repository's git hooks (unit 0.9).
#
# Runs automatically from package.json's `prepare` script, i.e. on `npm install`
# and `npm ci`, so a fresh clone is protected as soon as dependencies are
# installed. Safe to run repeatedly.
#
# ALWAYS EXITS 0. It is wired into `prepare`, which npm also runs during the
# Railpack production build; a hook installer must never be able to fail a
# deploy. Every skip reason is announced, never swallowed.
#
# WHY A SHIM INSTEAD OF core.hooksPath
#   Pointing core.hooksPath at .githooks/ would disable everything already in
#   .git/hooks — and this repo has four live git-lfs hooks there (post-checkout,
#   post-commit, post-merge, pre-push). Installing a two-line shim leaves those
#   alone. The shim never drifts, because all the real logic stays in the
#   tracked .githooks/pre-commit that it execs.
set -uo pipefail

say() { printf '[install-git-hooks] %s\n' "$*"; }

GIT_DIR="$(git rev-parse --git-dir 2>/dev/null || true)"
if [ -z "$GIT_DIR" ]; then
  say "not a git working copy (build/tarball install?) — nothing to do."
  exit 0
fi

REPO_ROOT="$(git rev-parse --show-toplevel 2>/dev/null || true)"
SOURCE="$REPO_ROOT/.githooks/pre-commit"
if [ ! -f "$SOURCE" ]; then
  say "WARNING: .githooks/pre-commit is missing — secret scanning is NOT installed."
  exit 0
fi
chmod +x "$SOURCE" 2>/dev/null || true

HOOKS_DIR="$(git rev-parse --git-path hooks 2>/dev/null || echo "$GIT_DIR/hooks")"
mkdir -p "$HOOKS_DIR" 2>/dev/null || { say "cannot create $HOOKS_DIR — skipping."; exit 0; }

TARGET="$HOOKS_DIR/pre-commit"
MARKER="sentire-secret-scan-shim"

# Refuse to clobber a hand-written hook that is not ours.
if [ -f "$TARGET" ] && ! grep -q "$MARKER" "$TARGET" 2>/dev/null; then
  say "WARNING: $TARGET already exists and is not ours — leaving it alone."
  say "         Secret scanning is NOT active. Merge it in by hand, or move it aside and re-run."
  exit 0
fi

cat > "$TARGET" <<'SHIM' || { say "could not write $TARGET — skipping."; exit 0; }
#!/usr/bin/env sh
# sentire-secret-scan-shim — generated by scripts/install-git-hooks.sh. Do not edit.
# The real hook is the tracked .githooks/pre-commit; this only forwards to it.
#
# Linked worktrees SHARE this hooks directory with the main worktree, but each
# has its own checkout. A worktree sitting on a branch from before unit 0.9 has
# no .githooks/ at all, so forwarding blindly would make `git commit` fail with
# exec: not found on branches that never asked for a hook. Fail OPEN in that
# case: no hook is the pre-0.9 status quo, not a security decision.
HOOK="$(git rev-parse --show-toplevel)/.githooks/pre-commit"
[ -x "$HOOK" ] || exit 0
exec "$HOOK" "$@"
SHIM

chmod +x "$TARGET" 2>/dev/null || true
say "pre-commit secret scan installed at $TARGET"
say "bypass in an emergency with: git commit --no-verify"
exit 0
