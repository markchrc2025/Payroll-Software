#!/usr/bin/env node
// PAY-73: writes ops/backup-check/Dockerfile with check.sh and run.sh inside
// it. Dokploy gives this app an empty build context, so the image cannot COPY
// files from the repository; the scripts travel in the Dockerfile instead.
// Edit check.sh or run.sh, then run: node ops/backup-check/build-dockerfile.mjs
// (pay73-backup-check T5 fails if the Dockerfile is out of date).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const embed = (name, tag) => {
  const body = readFileSync(join(here, name), "utf8");
  if (body.includes(tag)) throw new Error(`${name} contains ${tag}`);
  return `COPY --chmod=755 <<'${tag}' /opt/backup-check/${name}\n${body.endsWith("\n") ? body : body + "\n"}${tag}\n`;
};

export function dockerfile() {
  return `# syntax=docker/dockerfile:1
# GENERATED by ops/backup-check/build-dockerfile.mjs from check.sh and run.sh.
# Do not edit by hand.
#
# PAY-73: the daily backup check (Mark, 25 Nov 2026: backups stay on RustFS on
# the mail server). PostgreSQL 18 to match the live server, so pg_restore can
# read Dokploy's dumps and a throwaway server is right here to restore into.
# The S3 client is Debian's own awscli package, so nothing is downloaded from
# outside the Debian archive.
FROM postgres:18-bookworm
RUN apt-get update \\
 && apt-get install -y --no-install-recommends awscli jq ca-certificates util-linux \\
 && rm -rf /var/lib/apt/lists/*
# /backups is the files copy; a Docker volume mounted here starts with this
# owner, so the check (running as postgres) can write to it.
RUN mkdir -p /backups /opt/backup-check && chown postgres:postgres /backups
${embed("check.sh", "PAY73_CHECK_SH_END")}${embed("run.sh", "PAY73_RUN_SH_END")}USER postgres
WORKDIR /tmp
ENTRYPOINT ["/opt/backup-check/run.sh"]
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(here, "Dockerfile"), dockerfile());
  console.log("wrote ops/backup-check/Dockerfile");
}
